/// The shared icon and typography for point-of-interest labels.
pub(super) fn poi_label<'a>(
    style: &'a mut Style,
    poi: &SourceLayer,
    id: &str,
) -> AttachedLayer<'a, Symbol> {
    style
        .symbol(poi, id)
        .icon_image("{class}_11")
        .text_font([ITALIC])
        .text_max_width(9.0)
        .text_size(12.0)
        .text_halo("#ffffff", 1.0)
        .text_halo_blur(0.5)
}

